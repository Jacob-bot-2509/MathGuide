"""文档生成:当前对话/问题归纳的问答导出,以及按独立要求生成带依据的文档。

约束:
- 问答导出不调用 LLM 改写答案,直接按原问答排版,避免把解答改坏;
- 独立要求先检索知识库,再生成大纲与分节正文;每节必须引用检索到的依据,
  没有依据就不写正文,返回 gaps 让用户补材料;
- PDF 复用 doc.py 的 KaTeX + Edge 管线;Markdown/Word 也从同一份结构化文档渲染。
"""
from __future__ import annotations

import asyncio
import re
import time
from io import BytesIO

from starlette.exceptions import HTTPException
from starlette.requests import Request
from starlette.responses import JSONResponse, Response

import doc
import rag
from chat import _rate_check, _record, require_auth
from http_utils import read_json_object

MAX_ITEMS = 20
MAX_TOTAL_CHARS = 40000
MAX_SECTIONS = 6
MAX_SECTION_POINTS = 6
CHAT_MESSAGES_MAX = 80
QUESTION_MAX = 400
ANSWER_MAX = 8000


def _lang(value: object, text: str = "") -> str:
    if value in ("zh", "en"):
        return str(value)
    return "zh" if re.search(r"[一-鿿]", text) else "en"


def _clean_text(value: object, limit: int) -> str:
    return str(value or "").strip()[:limit]


def _clean_markdown(text: str) -> str:
    """PDF 渲染器只认纯文本 + LaTeX;去掉 LLM/原回答里的 Markdown 标记。"""
    text = re.sub(r"```[^\n]*\n?", "", text)
    text = re.sub(r"^\s{0,3}#{1,6}\s*", "", text, flags=re.M)
    text = re.sub(r"^\s*---\s*$", "", text, flags=re.M)
    text = re.sub(r"^\s*>\s?", "", text, flags=re.M)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = text.replace("**", "").replace("__", "")
    text = re.sub(r"^\s*[-*]\s+", "• ", text, flags=re.M)
    return text.strip()


def _paragraphs(text: str) -> list[str]:
    text = _clean_markdown(text)
    parts = [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]
    return parts or ([text] if text else [])


def _format(value: object) -> str:
    return value if value in ("pdf", "md", "docx") else "pdf"


def _qa_document(items: list[dict], lang: str, source: str) -> dict:
    zh = lang == "zh"
    sections = []
    refs = []
    for index, item in enumerate(items):
        question = _clean_text(item.get("question"), QUESTION_MAX)
        answer = _clean_text(item.get("answer"), ANSWER_MAX)
        if not question or not answer:
            continue
        sections.append({
            "heading": f"{index + 1}. {question[:100]}",
            "paragraphs": _paragraphs(answer),
        })
        refs.append({
            "id": index + 1,
            "title": question[:300],
            "source": source[:40],
            "url": "",
        })
    return {
        "title": ("问题解答文档" if zh else "Question & Answer Document"),
        "abstract": (
            f"本文档由 MathGuide 根据{source}生成,共 {len(sections)} 题。"
            if zh else
            f"Generated by MathGuide from {source}; {len(sections)} questions."
        ),
        "keywords": [],
        "sections": sections,
        "references": refs,
    }


def _markdown(document: dict, lang: str) -> str:
    d = doc._normalize_doc(document, "", lang)
    zh = lang == "zh"
    lines = [f"# {d['title']}", ""]
    if d.get("abstract"):
        lines += [f"> {d['abstract']}", ""]
    for section in d.get("sections", []):
        lines += [f"## {section['heading']}", ""]
        for paragraph in section.get("paragraphs", []):
            lines += [paragraph, ""]
    if d.get("references"):
        lines += [f"## {'参考依据' if zh else 'References'}", ""]
        for ref in d["references"]:
            source = f" — {ref['source']}" if ref.get("source") else ""
            lines.append(f"- [{ref['id']}] {ref['title']}{source}")
    return "\n".join(lines).rstrip() + "\n"


def _docx_bytes(document: dict, lang: str) -> bytes:
    from docx import Document

    d = doc._normalize_doc(document, "", lang)
    out = Document()
    out.add_heading(d["title"], level=0)
    if d.get("abstract"):
        out.add_paragraph(d["abstract"])
    for section in d.get("sections", []):
        out.add_heading(section["heading"], level=1)
        for paragraph in section.get("paragraphs", []):
            out.add_paragraph(paragraph)
    if d.get("references"):
        out.add_heading("参考依据" if lang == "zh" else "References", level=1)
        for ref in d["references"]:
            source = f" — {ref['source']}" if ref.get("source") else ""
            out.add_paragraph(f"[{ref['id']}] {ref['title']}{source}")
    buffer = BytesIO()
    out.save(buffer)
    return buffer.getvalue()


async def _render(document: dict, lang: str, fmt: str, prefix: str) -> Response:
    if fmt == "pdf":
        brand = "问题解答 / Q&A" if prefix == "mg-qa" else "文档 / DOCUMENT"
        data = await asyncio.to_thread(doc.render_pdf_bytes, document, lang, brand)
        if data is None:
            raise HTTPException(500, "pdf render failed")
        media, ext = "application/pdf", "pdf"
    elif fmt == "md":
        data, media, ext = _markdown(document, lang).encode("utf-8"), "text/markdown; charset=utf-8", "md"
    else:
        data = await asyncio.to_thread(_docx_bytes, document, lang)
        media, ext = "application/vnd.openxmlformats-officedocument.wordprocessingml.document", "docx"
    filename = f"{prefix}-{time.strftime('%Y%m%d')}.{ext}"
    return Response(data, media_type=media,
                    headers={"Content-Disposition": f'attachment; filename="{filename}"'})


def _evidence_list(chunks: list[tuple]) -> list[dict]:
    evidence = []
    for index, item in enumerate(chunks):
        chunk = item[0] if isinstance(item, tuple) else item
        evidence.append({
            "id": f"E{index + 1}",
            "title": _clean_text(getattr(chunk, "title", ""), 120),
            "section": _clean_text(getattr(chunk, "section", ""), 80),
            "text": _clean_text(getattr(chunk, "text", ""), 1200),
        })
    return evidence


def _fallback_outline(evidence: list[dict], request: str, lang: str) -> dict:
    groups: dict[str, list[dict]] = {}
    for item in evidence:
        key = item["title"] or item["section"] or ("知识片段" if lang == "zh" else "Knowledge")
        groups.setdefault(key, []).append(item)
    sections = []
    for title, items in list(groups.items())[:MAX_SECTIONS]:
        sections.append({
            "heading": title[:100],
            "points": [items[0]["text"][:160]],
            "evidence_ids": [item["id"] for item in items],
            "has_evidence": True,
        })
    return {
        "title": request[:60] or ("文档" if lang == "zh" else "Document"),
        "sections": sections,
        "gaps": [],
    }


def _normalize_outline(obj: dict, evidence: list[dict], request: str, lang: str) -> dict:
    valid_ids = {item["id"] for item in evidence}
    sections = []
    gaps = []
    for raw in obj.get("sections") if isinstance(obj.get("sections"), list) else []:
        if not isinstance(raw, dict):
            continue
        heading = _clean_text(raw.get("heading"), 100)
        if not heading:
            continue
        points = [
            _clean_text(point, 200)
            for point in (raw.get("points") if isinstance(raw.get("points"), list) else [])
            if _clean_text(point, 200)
        ][:MAX_SECTION_POINTS]
        ids = [
            str(item)
            for item in (raw.get("evidence_ids") if isinstance(raw.get("evidence_ids"), list) else [])
            if str(item) in valid_ids
        ][:8]
        if not ids:
            gaps.append(heading)
        sections.append({
            "heading": heading,
            "points": points,
            "evidence_ids": ids,
            "has_evidence": bool(ids),
        })
        if len(sections) >= MAX_SECTIONS:
            break
    if not sections:
        return _fallback_outline(evidence, request, lang)
    raw_gaps = obj.get("gaps") if isinstance(obj.get("gaps"), list) else []
    for gap in raw_gaps[:8]:
        text = _clean_text(gap, 160)
        if text:
            gaps.append(text)
    return {
        "title": _clean_text(obj.get("title"), 120) or request[:60],
        "sections": sections,
        "gaps": list(dict.fromkeys(gaps)),
    }


def _outline_system(lang: str) -> str:
    if lang == "en":
        return (
            "You are a document planner. Build an outline using ONLY the supplied evidence. "
            "Return strict JSON: {\"title\":str,\"sections\":[{\"heading\":str,\"points\":[str],"
            "\"evidence_ids\":[str]}],\"gaps\":[str]}. Every section must cite at least one "
            "evidence id. Do not invent facts or citations. 3-6 sections. No markdown fences."
        )
    return (
        "你是文档规划助手。只能依据给出的证据规划大纲,不得补充证据之外的事实。"
        "只输出严格 JSON:{\"title\":字符串,\"sections\":[{\"heading\":字符串,"
        "\"points\":[字符串],\"evidence_ids\":[字符串]}],\"gaps\":[字符串]}。"
        "每一节必须至少引用一个证据 id;证据不足的章节放进 gaps,不要硬编。"
        "3~6 节,不要 markdown 代码块。"
    )


def _outline_user(request: str, evidence: list[dict]) -> str:
    blocks = "\n\n".join(
        f"[{item['id']}] {item['title']} · {item['section']}\n{item['text']}"
        for item in evidence
    )
    return f"用户要求:\n{request}\n\n可用依据:\n{blocks}"


async def _collect_llm(system: str, user: str, *, max_tokens: int) -> str:
    full: list[str] = []
    async for delta in rag.llm.stream_chat(
            system, user, role=rag.llm.pick("deep"), fallback=True,
            max_tokens=max_tokens, thinking=False):
        full.append(delta)
    return "".join(full)


def _section_system(lang: str) -> str:
    if lang == "en":
        return (
            "You are an academic document writer. Use ONLY the supplied evidence. "
            "Never invent facts, theorems, numbers or citations. If the evidence cannot "
            "support the section, output exactly [NO EVIDENCE] and nothing else. "
            "Write clear prose; use LaTeX for formulas ($...$ inline, $$...$$ display)."
        )
    return (
        "你是学术文档撰写助手。只能使用给出的证据,不得编造事实、定理、数字或引用。"
        "如果证据不足以支撑本节,只输出 [未找到依据],不要写其他内容。"
        "正文用清晰书面语;公式用 LaTeX(行内 $...$,块级 $$...$$)。"
    )


async def questions(request: Request) -> JSONResponse:
    """从当前会话消息中提取可导出的问答对;不调用 LLM,避免编出没问过的问题。"""
    require_auth(request)
    body = await read_json_object(request)
    messages = body.get("messages") if isinstance(body.get("messages"), list) else []
    items = []
    seen = set()
    for index, message in enumerate(messages[:CHAT_MESSAGES_MAX]):
        if not isinstance(message, dict) or message.get("role") != "user":
            continue
        if message.get("cmd") or message.get("chitchat"):
            continue
        content = _clean_text(message.get("content"), QUESTION_MAX)
        if not content or content.startswith("[attach:"):
            continue
        key = re.sub(r"\s+", " ", content).lower()
        if key in seen:
            continue
        seen.add(key)
        answer = ""
        for nxt in messages[index + 1:CHAT_MESSAGES_MAX]:
            if not isinstance(nxt, dict):
                continue
            if nxt.get("role") == "user":
                break
            if nxt.get("role") == "assistant":
                answer = _clean_text(nxt.get("content"), ANSWER_MAX)
                if answer:
                    break
        items.append({"id": index, "question": content, "has_answer": bool(answer)})
        if len(items) >= MAX_ITEMS:
            break
    return JSONResponse({"items": items})


async def qa_export(request: Request) -> Response | JSONResponse:
    rec = require_auth(request)
    _rate_check(str(rec.get("uid") or rec.get("phone") or ""))
    body = await read_json_object(request)
    raw_items = body.get("items") if isinstance(body.get("items"), list) else []
    items = []
    total = 0
    for item in raw_items[:MAX_ITEMS]:
        if not isinstance(item, dict):
            continue
        question = _clean_text(item.get("question"), QUESTION_MAX)
        answer = _clean_text(item.get("answer"), ANSWER_MAX)
        if not question or not answer:
            continue
        total += len(question) + len(answer)
        if total > MAX_TOTAL_CHARS:
            return JSONResponse({"detail": "too much content"}, status_code=413)
        items.append({"question": question, "answer": answer})
    if not items:
        return JSONResponse({"detail": "empty items"}, status_code=400)
    lang = _lang(body.get("lang"), " ".join(i["question"] for i in items))
    source = _clean_text(body.get("source"), 40) or ("当前对话" if lang == "zh" else "Current chat")
    document = _qa_document(items, lang, source)
    try:
        await asyncio.to_thread(_record, rec, cmd="生成文档", prompt_len=total,
                                reply_len=0, role="deep", research=False)
    except Exception as exc:  # noqa: BLE001
        print(f"[docgen] 记账失败: {exc}")
    return await _render(document, lang, _format(body.get("format")), "mg-qa")


async def outline(request: Request) -> JSONResponse:
    rec = require_auth(request)
    _rate_check(str(rec.get("uid") or rec.get("phone") or ""))
    body = await read_json_object(request)
    text = _clean_text(body.get("request"), 2000)
    if not text:
        return JSONResponse({"detail": "empty request"}, status_code=400)
    lang = _lang(body.get("lang"), text)
    try:
        evidence = _evidence_list(await asyncio.to_thread(rag.search, text, 8))
    except Exception as exc:  # noqa: BLE001
        print(f"[docgen] 大纲检索失败: {exc}")
        return JSONResponse({"error": "retrieval_failed"}, status_code=503)
    if not evidence:
        return JSONResponse({"error": "no_evidence", "gaps": [text[:120]]}, status_code=422)

    parsed = None
    if rag.llm.is_configured():
        try:
            raw = await _collect_llm(_outline_system(lang), _outline_user(text, evidence),
                                     max_tokens=2200)
            parsed = doc._extract_json(raw)
        except Exception as exc:  # noqa: BLE001
            print(f"[docgen] 大纲生成失败,使用检索片段兜底: {exc}")
    plan = _normalize_outline(parsed or {}, evidence, text, lang)
    return JSONResponse({
        "title": plan["title"],
        "sections": plan["sections"],
        "gaps": plan["gaps"],
        "evidence": [
            {"id": item["id"], "title": item["title"], "section": item["section"]}
            for item in evidence
        ],
    })


async def generate(request: Request) -> JSONResponse:
    rec = require_auth(request)
    _rate_check(str(rec.get("uid") or rec.get("phone") or ""))
    body = await read_json_object(request)
    text = _clean_text(body.get("request"), 2000)
    plan = body.get("outline") if isinstance(body.get("outline"), dict) else {}
    raw_sections = plan.get("sections") if isinstance(plan.get("sections"), list) else []
    if not text or not raw_sections:
        return JSONResponse({"detail": "empty outline"}, status_code=400)
    if not rag.llm.is_configured():
        return JSONResponse({"error": "llm_unavailable"}, status_code=503)

    lang = _lang(body.get("lang"), text)
    try:
        evidence = _evidence_list(await asyncio.to_thread(rag.search, text, 8))
    except Exception as exc:  # noqa: BLE001
        print(f"[docgen] 分节检索失败: {exc}")
        return JSONResponse({"error": "retrieval_failed"}, status_code=503)
    if not evidence:
        return JSONResponse({"error": "no_evidence"}, status_code=422)
    ev_map = {item["id"]: item for item in evidence}

    sections = []
    gaps = []
    used: set[str] = set()
    total_reply = 0
    for raw in raw_sections[:MAX_SECTIONS]:
        if not isinstance(raw, dict):
            continue
        heading = _clean_text(raw.get("heading"), 120)
        if not heading:
            continue
        ids = [
            str(item) for item in (raw.get("evidence_ids") if isinstance(raw.get("evidence_ids"), list) else [])
            if str(item) in ev_map
        ][:8]
        if not ids:
            gaps.append(heading)
            continue
        points = [
            _clean_text(point, 200)
            for point in (raw.get("points") if isinstance(raw.get("points"), list) else [])
            if _clean_text(point, 200)
        ][:MAX_SECTION_POINTS]
        blocks = "\n\n".join(
            f"[{eid}] {ev_map[eid]['title']} · {ev_map[eid]['section']}\n{ev_map[eid]['text']}"
            for eid in ids
        )
        user = (
            f"文档要求:\n{text}\n\n本节标题:\n{heading}\n\n本节要点:\n"
            + ("\n".join(f"- {p}" for p in points) if points else "(未指定)")
            + f"\n\n可用依据:\n{blocks}"
        )
        try:
            raw_text = await _collect_llm(_section_system(lang), user, max_tokens=1800)
        except Exception as exc:  # noqa: BLE001
            print(f"[docgen] 分节生成失败: {exc}")
            gaps.append(heading)
            continue
        if not raw_text.strip() or "[未找到依据]" in raw_text or "[NO EVIDENCE]" in raw_text:
            gaps.append(heading)
            continue
        paragraphs = _paragraphs(raw_text)[:20]
        if not paragraphs:
            gaps.append(heading)
            continue
        sections.append({"heading": heading, "paragraphs": paragraphs})
        used.update(ids)
        total_reply += sum(len(p) for p in paragraphs)

    if not sections:
        return JSONResponse({"error": "no_evidence", "gaps": gaps}, status_code=422)

    references = []
    for eid in sorted(used, key=lambda value: int(value[1:])):
        item = ev_map[eid]
        references.append({
            "id": len(references) + 1,
            "title": item["title"][:300],
            "source": "知识库",
            "url": "",
        })
    document = {
        "title": _clean_text(plan.get("title"), 120) or text[:60],
        "abstract": (
            "本文档严格依据 MathGuide 知识库中的检索片段生成;未能找到依据的章节已跳过。"
            if lang == "zh" else
            "Generated strictly from retrieved knowledge-base evidence; unsupported sections were skipped."
        ),
        "keywords": [],
        "sections": sections,
        "references": references,
    }
    try:
        await asyncio.to_thread(_record, rec, cmd="生成文档", prompt_len=len(text),
                                reply_len=total_reply, role="deep", research=False)
    except Exception as exc:  # noqa: BLE001
        print(f"[docgen] 记账失败: {exc}")
    return JSONResponse({"document": document, "gaps": gaps})


async def render(request: Request) -> Response | JSONResponse:
    """把前端已生成的结构化文档导出为 PDF/Markdown/Word。"""
    rec = require_auth(request)
    _rate_check(str(rec.get("uid") or rec.get("phone") or ""))
    body = await read_json_object(request)
    document = body.get("document") if isinstance(body.get("document"), dict) else None
    if not document or not isinstance(document.get("sections"), list):
        return JSONResponse({"detail": "empty document"}, status_code=400)
    sections = [item for item in document["sections"] if isinstance(item, dict)]
    if not sections or len(sections) > 20:
        return JSONResponse({"detail": "invalid document"}, status_code=400)
    total_chars = sum(
        len(str(paragraph))
        for section in sections
        for paragraph in (section.get("paragraphs") if isinstance(section.get("paragraphs"), list) else [])
    )
    if total_chars > 100_000:
        return JSONResponse({"detail": "document too large"}, status_code=413)
    lang = _lang(body.get("lang"))
    return await _render(document, lang, _format(body.get("format")), "mg-document")
